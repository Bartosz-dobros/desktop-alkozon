class I18nService:
    _instance = None

    def __init__(self):
        self._current_lang = "pl"

    @classmethod
    def get_instance(cls) -> "I18nService":
        if cls._instance is None:
            cls._instance = cls()
        return cls._instance

    @property
    def current_lang(self) -> str:
        return self._current_lang

    @current_lang.setter
    def current_lang(self, lang: str) -> None:
        if lang in ("pl", "en"):
            self._current_lang = lang

    @property
    def is_polish(self) -> bool:
        return self._current_lang == "pl"

    def t(self, key: str, **kwargs) -> str:
        entry = TRANSLATIONS.get(key, {})
        text = entry.get(self._current_lang, key)
        if kwargs:
            return text.format(**kwargs)
        return text


i18n = I18nService.get_instance()
